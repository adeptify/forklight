  var LANG_KEY = "forklight.hub.lang";
  var lang = "zh";

  function detectLang() {
    try {
      var stored = global.localStorage && global.localStorage.getItem(LANG_KEY);
      if (stored === "zh" || stored === "en") return stored;
    } catch (_) { /* ignore */ }
    var nav = (global.navigator && (global.navigator.language || global.navigator.userLanguage)) || "zh";
    return /^zh\b/i.test(nav) ? "zh" : "en";
  }

  function t(key, vars) {
    var bag = STRINGS[lang] || STRINGS.zh;
    var parts = String(key).split(".");
    var cur = bag;
    for (var i = 0; i < parts.length; i++) {
      if (cur == null || typeof cur !== "object") { cur = undefined; break; }
      cur = cur[parts[i]];
    }
    if (cur === undefined || cur === null) {
      // fallback en
      cur = STRINGS.en;
      for (var j = 0; j < parts.length; j++) {
        if (cur == null || typeof cur !== "object") { cur = key; break; }
        cur = cur[parts[j]];
        if (j === parts.length - 1 && cur === undefined) cur = key;
      }
    }
    var out = typeof cur === "string" ? cur : key;
    if (vars && typeof vars === "object") {
      Object.keys(vars).forEach(function (k) {
        out = out.split("{" + k + "}").join(String(vars[k]));
        out = out.split("${" + k + "}").join(String(vars[k]));
      });
    }
    return out;
  }

  function pageMeta(tab) {
    var bag = STRINGS[lang] || STRINGS.zh;
    var p = (bag.page && bag.page[tab]) || (STRINGS.en.page && STRINGS.en.page[tab]);
    return p || { title: tab, sub: "" };
  }

  function getLang() { return lang; }

  function setLang(next) {
    if (next !== "zh" && next !== "en") return;
    lang = next;
    try {
      if (global.localStorage) global.localStorage.setItem(LANG_KEY, lang);
    } catch (_) { /* ignore */ }
    if (global.document && global.document.documentElement) {
      global.document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    }
    if (typeof global.onForklightLangChange === "function") {
      global.onForklightLangChange(lang);
    }
  }

  lang = detectLang();

  global.ForklightI18n = {
    t: t,
    pageMeta: pageMeta,
    getLang: getLang,
    setLang: setLang,
    detectLang: detectLang,
    STRINGS: STRINGS
  };
